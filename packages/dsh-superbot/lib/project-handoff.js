/**
 * Per-project handoff projection.
 *
 * This is the durable bridge between "Superbot on" and "Superbot off":
 *   - it lives in the project (SUPERBOT-HANDOFF.md), so a normal DSH session or
 *     a human can continue without the plugin;
 *   - it is a bounded projection (target < 4 KB), never a transcript, so the
 *     next agent does not pay for history;
 *   - the append-only ledger remains the source of truth; this file is
 *     regenerated from it and can be deleted safely.
 */

import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const HANDOFF_FILE_NAME = 'SUPERBOT-HANDOFF.md'
const MARKER = '# Superbot handoff'
const MAX_TEXT = 240
const MAX_ITEMS = 10
const MAX_BYTES = 4_500

const text = (value, fallback = '') => {
  if (typeof value !== 'string') return fallback
  const trimmed = value.replace(/\s+/g, ' ').trim()
  if (trimmed === '') return fallback
  return trimmed.length > MAX_TEXT ? `${trimmed.slice(0, MAX_TEXT - 1)}…` : trimmed
}

const time = (iso) => {
  if (typeof iso !== 'string') return 'unknown'
  const ms = Date.parse(iso)
  return Number.isFinite(ms) ? new Date(ms).toISOString().replace('T', ' ').slice(0, 16) : 'unknown'
}

const latest = (list) => (Array.isArray(list) ? list.filter(Boolean).sort((left, right) => String(left.submittedAt ?? '').localeCompare(String(right.submittedAt ?? '')) || Number(left.seq ?? 0) - Number(right.seq ?? 0)).at(-1) : undefined)

/**
 * @param {{
 *   project: {projectId: string, title?: string, path?: string|null},
 *   requirements?: object[], tasks?: object[], runs?: object[], reviews?: object[],
 *   now?: number,
 * }} input
 * @returns {string}
 */
export function renderProjectHandoff({ project, requirements = [], tasks = [], runs = [], reviews = [], now = Date.now() }) {
  const projectId = String(project?.projectId ?? project?.workspaceId ?? '')
  const title = text(project?.title, projectId || 'project')
  const projectTasks = (Array.isArray(tasks) ? tasks : []).filter((task) => task.projectId === projectId)
  const projectReqs = (Array.isArray(requirements) ? requirements : []).filter((req) => req.projectId === projectId)
  const requirement = latest(projectReqs.map((req) => ({ ...req, submittedAt: req.submittedAt ?? req.createdAt })))

  const latestVerifier = new Map()
  for (const review of Array.isArray(reviews) ? reviews : []) {
    if (review.source !== 'verifier') continue
    const task = projectTasks.find((entry) => entry.id === review.taskId)
    if (task === undefined) continue
    const current = latestVerifier.get(task.id)
    if (current === undefined || String(review.submittedAt ?? '') >= String(current.submittedAt ?? '')) latestVerifier.set(task.id, review)
  }

  const classify = (task) => {
    if (task.status === 'done') return 'done'
    if (task.status === 'canceled') return 'canceled'
    if (task.status === 'in_review') return 'needs-you'
    if (latestVerifier.get(task.id)?.verdict === 'fail') return 'rework'
    if (task.status === 'in_progress') return 'executing'
    return 'queued'
  }
  const groups = new Map()
  for (const task of projectTasks) {
    const kind = classify(task)
    const list = groups.get(kind) ?? []
    list.push(task)
    groups.set(kind, list)
  }
  const pick = (kind) => (groups.get(kind) ?? []).slice(0, MAX_ITEMS)
  const active = [...pick('needs-you'), ...pick('rework'), ...pick('executing'), ...pick('queued')]
  const doneCount = (groups.get('done') ?? []).length
  const openCount = active.length
  const commands = []
  for (const task of active) {
    for (const entry of Array.isArray(task.acceptanceCommands) ? task.acceptanceCommands : []) {
      const command = typeof entry?.command === 'string' ? entry.command : entry
      if (typeof command === 'string' && !commands.includes(command)) commands.push(command)
    }
  }
  const constraints = []
  for (const task of active) {
    for (const value of [...(Array.isArray(task.constraints) ? task.constraints : []), ...(Array.isArray(task.nonGoals) ? task.nonGoals : [])]) {
      const line = text(value)
      if (line !== '' && !constraints.includes(line)) constraints.push(line)
    }
  }

  const lines = [
    `${MARKER} — ${title}`,
    '',
    'Generated by Superbot from the project ledger. Read this first; it is the bounded',
    'context needed to continue without Superbot. The ledger stays the source of truth.',
    '',
    `- Project: ${projectId}${project?.path ? ` (${project.path})` : ''}`,
    `- Updated: ${time(new Date(now).toISOString())}`,
    `- Open tasks: ${openCount} · Done: ${doneCount}`,
    '',
    '## Goal',
    requirement === undefined ? '- (no recorded requirement)' : `- ${text(requirement.title)}${requirement.text ? `: ${text(requirement.text)}` : ''}`,
    '',
  ]

  const kindLabel = { 'needs-you': 'Needs your decision', rework: 'Rework', executing: 'Executing', queued: 'Queued' }
  for (const kind of ['needs-you', 'rework', 'executing', 'queued']) {
    const list = pick(kind)
    if (list.length === 0) continue
    lines.push(`## ${kindLabel[kind]}`)
    for (const task of list) {
      const verifier = latestVerifier.get(task.id)
      const detail = kind === 'needs-you' ? 'in_review; human acceptance required' : kind === 'rework' ? `verifier: ${text(verifier?.notes, 'fail')}` : task.status
      lines.push(`- ${task.id} — ${text(task.title, task.id)} [${detail}]`)
      const acceptance = Array.isArray(task.acceptance) ? task.acceptance.filter((item) => typeof item === 'string' && item.trim() !== '') : []
      if (acceptance.length > 0) lines.push(`  - acceptance: ${acceptance.slice(0, 3).map((item) => text(item, '')).filter(Boolean).join(' | ')}`)
    }
    lines.push('')
  }

  if (commands.length > 0) {
    lines.push('## Machine acceptance commands (run in this project; never weaken)')
    for (const command of commands.slice(0, 6)) lines.push(`- \`${command}\``)
    lines.push('')
  }
  if (constraints.length > 0) {
    lines.push('## Constraints / non-goals')
    for (const line of constraints.slice(0, 6)) lines.push(`- ${line}`)
    lines.push('')
  }
  lines.push('## How to continue without Superbot')
  lines.push('1. Read this file and the project files; do not ask for the old chat transcript.')
  lines.push('2. Worker self-reports are claims, not evidence; run the acceptance commands yourself.')
  lines.push('3. Project map/harness: SUPERBOT-PROJECT.md (when present); do not edit generated files by hand.')
  lines.push('4. Re-enable Superbot to resume ledger-managed tasks; unfinished work is listed above.')

  let output = lines.join('\n')
  if (Buffer.byteLength(output, 'utf8') > MAX_BYTES) {
    output = `${Buffer.from(output, 'utf8').subarray(0, MAX_BYTES).toString('utf8').replace(/\n[^\n]*$/, '\n')}\n…\n`
  }
  return output
}

/** Gather only the ledger rows needed for one project handoff. */
export function buildProjectHandoff({ store, project, now = Date.now() }) {
  if (store === undefined) throw new Error('project handoff requires a work store')
  return renderProjectHandoff({
    project,
    requirements: store.listRequirements(),
    tasks: store.listTasks(),
    runs: store.listRuns(),
    reviews: store.listReviews(),
    now,
  })
}

/**
 * Write a handoff into the project. Refuses to overwrite a foreign file.
 * @returns {{path: string, written: boolean, bytes: number, reason?: string}}
 */
export function writeProjectHandoff(projectPath, markdown, { fileName = HANDOFF_FILE_NAME } = {}) {
  if (typeof projectPath !== 'string' || projectPath.trim() === '') throw new Error('project path is required')
  const file = join(projectPath, fileName)
  if (existsSync(file)) {
    let existing = ''
    try { existing = readFileSync(file, 'utf8').slice(0, 200) } catch { existing = '' }
    if (!existing.startsWith(MARKER)) return { path: file, written: false, bytes: 0, reason: 'foreign-file' }
  }
  const bytes = Buffer.byteLength(markdown, 'utf8')
  const temp = `${file}.tmp-${process.pid}`
  writeFileSync(temp, markdown, { encoding: 'utf8', mode: 0o644 })
  renameSync(temp, file)
  return { path: file, written: true, bytes }
}
